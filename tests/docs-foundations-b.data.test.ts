import { spawnSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { describe, expect, it } from "vitest"
import { CONTRAST_ROWS, type ContrastRow } from "@/docs/content/foundations/_shared-b/contrast-data.generated"
import { ICON_DEMAND } from "@/docs/content/foundations/_shared-b/icon-demand"
import { search, score } from "@/docs/content/foundations/_shared-b/search"

const ROOT = process.cwd()
const DATA_FILE = path.join(ROOT, "src/docs/content/foundations/_shared-b/contrast-data.generated.ts")

function measure(): ContrastRow[] {
  const run = spawnSync(process.execPath, ["tools/check-tokens.mjs", "--contrast", "--json"], { cwd: ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })
  const report = JSON.parse(run.stdout) as { contrast: { scope: string; fg: string; bg: string; min: number; level: "error" | "warn"; status: string; ratio: number | null; fgHex: string; bgHex: string; purpose: string }[] }
  const pairs = (JSON.parse(fs.readFileSync(path.join(ROOT, "tools/contrast-pairs.json"), "utf8")) as { pairs: { section: string }[] }).pairs
  const rows = report.contrast.filter((r) => r.scope === ":root")
  return rows.map((r, i) => ({
    section: pairs[i]!.section,
    purpose: r.purpose,
    fg: r.fg,
    bg: r.bg,
    fgHex: r.fgHex,
    bgHex: r.bgHex,
    ratio: Math.round((r.ratio ?? 0) * 100) / 100,
    min: r.min,
    level: r.level,
  }))
}

function moduleSource(rows: readonly ContrastRow[]): string {
  const lines = rows.map((r) => `  ${JSON.stringify(r)},`)
  return `// GENERATED by tests/docs-foundations-b.data.test.ts (run it with UPDATE_CONTRAST=1) from \`node tools/check-tokens.mjs --contrast --json\` and
// tools/contrast-pairs.json: the Notebook rows of the contrast table, measured on the real tokens. A test compares this file with a fresh measurement,
// so it cannot drift from the palette. Do not edit by hand.

export interface ContrastRow {
  section: string
  purpose: string
  fg: string
  bg: string
  fgHex: string
  bgHex: string
  /** WCAG 2.x contrast ratio, two decimals. */
  ratio: number
  /** What the pair needs: 7 AAA text, 4.5 AA text, 3 non-text marks and large text, less for decorative hairlines. */
  min: number
  /** \`warn\` rows are known and explained on the page; they do not fail the token check. */
  level: "error" | "warn"
}

export const CONTRAST_ROWS: readonly ContrastRow[] = [
${lines.join("\n")}
]
`
}

describe("the contrast table on the accessibility page", () => {
  const fresh = measure()

  it.skipIf(!process.env.UPDATE_CONTRAST)("rewrites the generated table (UPDATE_CONTRAST=1)", () => {
    fs.writeFileSync(DATA_FILE, moduleSource(fresh))
  })

  it.skipIf(!!process.env.UPDATE_CONTRAST)("is what tools/check-tokens.mjs measures now, row for row", () => {
    expect(CONTRAST_ROWS.length).toBeGreaterThan(90)
    expect(CONTRAST_ROWS).toEqual(fresh)
  })

  it("only lists pairs that meet their minimum, apart from the explained warnings", () => {
    for (const r of CONTRAST_ROWS) {
      if (r.level === "warn") continue
      expect(r.ratio, `${r.fg} on ${r.bg}: ${r.purpose}`).toBeGreaterThanOrEqual(r.min - 0.005)
    }
    const known = CONTRAST_ROWS.filter((r) => r.level === "warn" && r.ratio < r.min)
    expect(known.length).toBeGreaterThanOrEqual(3)
  })
})

describe("the lucide usage sample", () => {
  it("is ordered by use and has no duplicates", () => {
    const uses = ICON_DEMAND.map(([, n]) => n)
    expect(uses).toEqual([...uses].sort((a, b) => b - a))
    expect(new Set(ICON_DEMAND.map(([n]) => n)).size).toBe(ICON_DEMAND.length)
  })
})

describe("gallery search", () => {
  const entries = [
    { id: "trash", aliases: ["trash-2"], tags: ["delete", "remove", "bin"] },
    { id: "triangle-alert", aliases: ["alert-triangle"], tags: ["warning", "attention"] },
    { id: "chevron-down", tags: ["caret", "dropdown"] },
    { id: "chevrons-up-down", tags: ["select"] },
    { id: "house", aliases: ["home"], tags: ["start"] },
  ]

  it("ranks the id above an alias above a tag", () => {
    const ids = (q: string) => search(entries, q).map((e) => e.id)
    expect(ids("chevron")).toEqual(["chevron-down", "chevrons-up-down"])
    expect(ids("home")).toEqual(["house"])
    expect(ids("warning")).toEqual(["triangle-alert"])
    expect(score("delete", entries[0]!)).toBeGreaterThan(0)
    expect(score("trash", entries[0]!)).toBeGreaterThan(score("delete", entries[0]!))
  })

  it("wants every word to match somewhere", () => {
    expect(search(entries, "chevron down").map((e) => e.id)[0]).toBe("chevron-down")
    expect(search(entries, "chevron zebra")).toEqual([])
  })

  it("puts what a pasted lucide name resolves to first", () => {
    const resolve = (n: string) => (n === "Trash2" ? "trash" : n)
    expect(search(entries, "Trash2", resolve)[0]!.id).toBe("trash")
    expect(search(entries, "", resolve)).toHaveLength(entries.length)
  })

  it("forgives a dropped letter", () => {
    expect(search(entries, "chvron").map((e) => e.id)).toContain("chevron-down")
  })
})
